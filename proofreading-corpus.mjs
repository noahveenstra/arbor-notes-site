// Hand-labeled sentences for the always-on proofreading cascade.
// expect: [] means the sentence must produce no underlines.
// A string in expect is a required replacement. "fragment" requires the
// detect-only fragment underline and nothing else.

function clean(category, sentences) {
  return sentences.map(function (item) {
    if (typeof item === "string") return { category: category, text: item, expect: [], protected: [] };
    return { category: category, text: item.text, expect: [], protected: item.protected || [] };
  });
}

function change(category, pairs) {
  return pairs.map(function (pair) { return { category: category, text: pair[0], expect: pair.slice(1) }; });
}

